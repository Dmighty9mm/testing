"""Generates ApolloSchemaData.java from the extracted schema JSON.

usage: python3 scripts/gen_apollo_schema.py docs/apollo/apollo-schema-1.0.2.json \
    sources/teavm/java/net/lax1dude/eaglercraft/v2_6/client/apollo/proto/ApolloSchemaData.java
"""
import json, sys, re
d = json.load(open(sys.argv[1]))
msgs, enums = d['messages'], d['enums']
# Any is not in the npm bundle's message list (protobufjs ships it separately)
msgs.setdefault('google.protobuf.Any', [
    {'id': 1, 'name': 'typeUrl', 'm': 'string', 'wt': 2, 'jstype': 'string|null'},
    {'id': 2, 'name': 'value', 'm': 'bytes', 'wt': 2, 'jstype': 'Uint8Array|null'}])
KIND = {'string': 's', 'bytes': 'y', 'bool': 'b', 'int32': 'i', 'uint32': 'I', 'int64': 'l', 'uint64': 'L',
        'sint32': 'z', 'sint64': 'Z', 'float': 'f', 'double': 'd', 'fixed32': 'x', 'fixed64': 'X',
        'sfixed32': 'w', 'sfixed64': 'W'}
def reftype(js):
    t = js.replace('|null', '')
    m = re.match(r'Array\.<(.+)>$', t)
    if m: t = m.group(1)
    m = re.match(r'Object\.<string,(.+)>$', t)
    if m: t = m.group(1)
    t = t.replace('|Long', '')
    return t
missing = set()
lines = []
for full in sorted(msgs):
    parts = []
    for f in sorted(msgs[full], key=lambda f: f['id']):
        js = f['jstype']
        rep = js.startswith('Array.<')
        is_map = js.startswith('Object.<')
        rt = reftype(js)
        m = f['m']
        if m == '?':
            m = 'string'
        if is_map:
            seg = rt.split('.'); seg[-1] = seg[-1][1:]; typ = '.'.join(seg)
            kind, tname = 'M', typ
        elif m == 'message':
            seg = rt.split('.'); seg[-1] = seg[-1][1:]; typ = '.'.join(seg)
            kind, tname = 'm', typ
        elif rt in enums:
            kind, tname = 'e', rt
        else:
            kind, tname = KIND[m], ''
        if kind in 'mM' and tname not in msgs: missing.add(tname)
        if kind == 'e' and tname not in enums: missing.add(tname)
        parts.append('%d:%s:%s%s%s' % (f['id'], f['name'], 'r' if rep else '', kind, (':' + tname) if tname else ''))
    lines.append((full, ';'.join(parts)))
if missing:
    print('MISSING', missing, file=sys.stderr); sys.exit(1)
out = []
out.append('package net.lax1dude.eaglercraft.v2_6.client.apollo.proto;')
out.append('')
out.append('/**')
out.append(' * GENERATED by scripts/gen_apollo_schema.py - do not edit by hand.')
out.append(' *')
out.append(' * <p>Field tables of the Apollo protocol messages (field numbers, wire')
out.append(' * kinds, nested types), as published in the lunar-apollo-protobuf 1.0.2')
out.append(' * descriptors. Only the facts needed to decode/encode the wire format are')
out.append(' * kept: no generated code is used.</p>')
out.append(' *')
out.append(' * <p>Message row: full name, then {@code id:name:[r]kind[:type]} fields')
out.append(' * joined by {@code ;}. Kinds: s string, y bytes, b bool, i int32, I uint32,')
out.append(' * l int64, L uint64, z sint32, Z sint64, f float, d double, x fixed32,')
out.append(' * X fixed64, w sfixed32, W sfixed64, e enum, m message, M map&lt;string,')
out.append(' * type&gt;; {@code r} = repeated. Enum row: full name, then')
out.append(' * {@code NAME=number} joined by {@code ;}.</p>')
out.append(' */')
out.append('final class ApolloSchemaData {')
out.append('')
out.append('        private ApolloSchemaData() {')
out.append('        }')
out.append('')
out.append('        static final String[] MESSAGES = {')
for full, spec in lines:
    out.append('                "%s", "%s",' % (full, spec))
out.append('        };')
out.append('')
out.append('        static final String[] ENUMS = {')
for full in sorted(enums):
    out.append('                "%s", "%s",' % (full, ';'.join('%s=%d' % (k, v) for k, v in sorted(enums[full].items(), key=lambda kv: kv[1]))))
out.append('        };')
out.append('}')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(lines), 'messages', len(enums), 'enums', file=sys.stderr)
